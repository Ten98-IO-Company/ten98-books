-- 0014: lookups by id that cost one row with or without table statistics (M2b slice b2).
--
-- Why. Every table is under the forced company policy, which adds company_id = ANY(<the scope>) to each scan. An index
-- that leads with company_id takes that condition as an index condition, and without statistics (a table never
-- analysed, as after a bulk load) the planner cannot tell such indexes apart: a lookup by company and id ties with any
-- other company-led index, and an unrelated predicate (a date, a group) breaks the tie, so the lookup reads the whole
-- company's rows, once for each row it serves. An index that does not lead with company_id cannot take the policy's
-- condition, so it always wins: one fetch. Measured as the application role on two companies of 100,000 vouchers each,
-- without statistics, with statistics, and with generic plans (docs/LEDGER.md, "Stock reads"; tests/lookup-by-id.integration.ts).
--
-- What. A unique index on id alone for voucher, ledger, stock_item, stock_unit and voucher_type (every guard and posting
-- lookup of those tables by id, and b2's reads of vouchers by id, then takes it), and inventory_line_item_idx rebuilt
-- without company_id (b2's reads seek an item's lines by item and location; with company_id in the key the location
-- index won without statistics). The id indexes only add an access path, and every guard keeps its code but one: the
-- unit check of stock_unit_guard, which the item index pulled onto the wrong side of a join (see its section).
--
-- Invariant the id indexes rely on: ids are generated by the server (the column default, uuidv7()) and never taken from a
-- request. Every create path inserts without an id, every create schema is strict (an id field is refused), the
-- application role may not update an id, and the company seeding (ledger_seed_company) and earlier migrations insert
-- without one. So two companies never share an id, and a uniqueness refusal can never tell a tenant that an id exists in
-- another company (docs/TENANCY.md). A row with a fixed or derived id in these tables would break this.
--
-- Locks (one transaction, held until it commits): each CREATE INDEX holds SHARE on its table while it builds (writes wait,
-- reads go on), and dropping the old item index holds ACCESS EXCLUSIVE on inventory_line. Plain builds, not CONCURRENTLY,
-- since nothing is deployed: measured at 200,026 vouchers and 52,002 item lines, 465 ms for the voucher index, 212 ms for
-- the item index, under 25 ms for each of the others.

-- Two rows with one id (possible only through direct SQL) would make a unique index fail and name the id in its error.
-- So such rows stop the migration first, counted per table under the all-company scope; the message names tables and
-- counts only, never an id. The operator corrects the rows and migrates again.
DO $$
DECLARE v_found text;
BEGIN
  PERFORM set_config('app.company_ids', coalesce((SELECT string_agg(id, ',') FROM workspace), ''), true);
  SELECT string_agg(format('%s: %s id(s)', name, shared), '; ' ORDER BY name) INTO v_found FROM (
    SELECT 'ledger' AS name, (SELECT count(*) FROM (SELECT id FROM ledger GROUP BY id HAVING count(*) > 1) d) AS shared
    UNION ALL SELECT 'stock_item', (SELECT count(*) FROM (SELECT id FROM stock_item GROUP BY id HAVING count(*) > 1) d)
    UNION ALL SELECT 'stock_unit', (SELECT count(*) FROM (SELECT id FROM stock_unit GROUP BY id HAVING count(*) > 1) d)
    UNION ALL SELECT 'voucher', (SELECT count(*) FROM (SELECT id FROM voucher GROUP BY id HAVING count(*) > 1) d)
    UNION ALL SELECT 'voucher_type', (SELECT count(*) FROM (SELECT id FROM voucher_type GROUP BY id HAVING count(*) > 1) d)
  ) tables WHERE shared > 0;
  PERFORM set_config('app.company_ids', '', true);
  IF v_found IS NOT NULL THEN
    RAISE EXCEPTION 'these tables hold ids shared by more than one row, which the unique id indexes cannot take; correct them first: %', v_found;
  END IF;
END $$;

-- Ids are unique across companies (see the invariant above).
CREATE UNIQUE INDEX voucher_id_key ON voucher (id);
CREATE UNIQUE INDEX ledger_id_key ON ledger (id);
CREATE UNIQUE INDEX stock_item_id_key ON stock_item (id);
CREATE UNIQUE INDEX stock_unit_id_key ON stock_unit (id);
CREATE UNIQUE INDEX voucher_type_id_key ON voucher_type (id);

-- The item index of 0013 without company_id. Its other users, the unit and item guards of 0013, probe it by item
-- without a company filter, so they keep it.
DROP INDEX inventory_line_item_idx;
CREATE INDEX inventory_line_item_idx ON inventory_line (item_id, location_id) INCLUDE (direction, quantity, amount);

-- ---- The unit check of stock_unit_guard (0013) ----

-- With stock_item_id_key, and without statistics, 0013's join of a unit's items to their openings is planned from the
-- other side: the company's opening rows, each with a probe of its item by id (3,008 fetches beside 3,000 stocked items
-- for a unit that has none). A unique index on id makes a probe by id look cheapest in any join, so this check drives
-- from the unit's items itself, as the item-line check beside it does: one probe of the openings per item of the unit,
-- by item only (the policy keeps the scope; as in 0008 and 0013, a company filter would let a cached generic plan read
-- the company's rows through a company-led key). Only that check changes; the rest is 0013's function. The API's copy
-- of the check is gone: this refusal is its answer (stock_unit_decimals, mapped to in_use).
CREATE OR REPLACE FUNCTION stock_unit_guard() RETURNS trigger LANGUAGE plpgsql SET search_path = public, pg_temp AS $$
DECLARE v_item uuid;
BEGIN
  IF TG_OP = 'DELETE' THEN PERFORM ledger_assert_scope(OLD.company_id); RETURN OLD; END IF;
  PERFORM ledger_assert_scope(NEW.company_id);
  IF TG_OP = 'UPDATE' AND NEW.decimals < OLD.decimals THEN
    IF current_setting('transaction_isolation') <> 'read committed' THEN
      RAISE EXCEPTION 'a unit''s decimals are lowered in READ COMMITTED transactions only' USING ERRCODE = '25001', CONSTRAINT = 'stock_unit_decimals';
    END IF;
    -- One probe of the openings per item of the unit, by item only, as below.
    FOR v_item IN SELECT id FROM stock_item WHERE unit_id = NEW.id LOOP
      IF EXISTS (SELECT 1 FROM stock_opening WHERE item_id = v_item) THEN
        RAISE EXCEPTION 'the decimals of a unit in use cannot be lowered' USING ERRCODE = '23514', CONSTRAINT = 'stock_unit_decimals';
      END IF;
    END LOOP;
    -- One probe of the item index per item of the unit. A join here is planned from the item lines' statistics: beside
    -- a few busy items, an item without lines looks common and the planner reads every line instead. The company is
    -- not a filter (as in 0008): with company_id = $1 a cached generic plan reads the company's rows through the
    -- primary key; the policy keeps the scope, and a row of another company with the same id can only make it refuse.
    FOR v_item IN SELECT id FROM stock_item WHERE unit_id = NEW.id LOOP
      IF EXISTS (SELECT 1 FROM inventory_line WHERE item_id = v_item) THEN
        RAISE EXCEPTION 'the decimals of a unit in use cannot be lowered' USING ERRCODE = '23514', CONSTRAINT = 'stock_unit_decimals';
      END IF;
    END LOOP;
  END IF;
  RETURN NEW;
END $$;
